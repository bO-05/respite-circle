/**
 * Deterministic language detection for ask intake.
 *
 * The decision service never guesses English slots for a non-English ask. A
 * confident non-English signal routes the ask to the coordinator with the
 * "bilingual person needed" flag, and no model call is made. This is a small,
 * dependency-free heuristic: enough to catch Spanish, French, Portuguese,
 * German, Italian, and any non-Latin script. It is not a translation tool.
 */

export type LanguageDetection = {
  /** Best two-letter guess, or `und` when a script has no match. */
  code: string;
  nonEnglish: boolean;
  confidence: number;
  /** Number of distinctive non-English word hits behind the verdict. */
  signals: number;
};


import { readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import {
  BRAND,
  BRAND_DESCRIPTION,
  BRAND_OG_ALT,
  BRAND_OG_TITLE,
  BRAND_STAMP,
  RING_PATH,
} from "@/lib/brand";
import { deploymentUrl } from "@/lib/site-url";

/**
 * The brand-asset contract (VAL-R5DES-003).
 *
 * These tests pin the files, the copy they carry, and the metadata
 * declarations. The rendered status codes, content types, pixel sizes,
 * masthead geometry and accessible names are asserted in
 * `tests/e2e/r5-brand.spec.ts`, because only a real build can prove them.
 */

const root = process.cwd();

function readText(file: string): string {
  return readFileSync(path.join(root, file), "utf8");
}

const ICON = readText("src/app/icon.svg");
const APPLE_ICON = readText("src/app/apple-icon.tsx");
const OPEN_GRAPH = readText("src/app/opengraph-image.tsx");
const LAYOUT = readText("src/app/layout.tsx");
const HEADER = readText("src/components/site-header.tsx");
const MARK_COMPONENT = readText("src/components/brand-mark.tsx");

describe("the icon route", () => {
  it("draws the open ring in accent on paper on a 32px grid", () => {
    expect(ICON).toContain('viewBox="0 0 32 32"');
    expect(ICON).toContain('width="32"');
    expect(ICON).toContain('height="32"');
    expect(ICON).toContain(`fill="${BRAND.paper}"`);
    expect(ICON).toContain(`stroke="${BRAND.accent}"`);
    expect(ICON).toContain(RING_PATH);
  });

  it("is a plain decorative drawing, not a titled image", () => {
    expect(ICON).not.toContain('role="img"');
    expect(ICON).not.toContain("<title");
    expect(ICON).not.toContain("aria-label");
  });
});

describe("the apple-touch icon", () => {
  it("is a 180x180 PNG generated by ImageResponse", () => {
    expect(APPLE_ICON).toContain('from "next/og"');
    expect(APPLE_ICON).toContain("export const size = { width: 180, height: 180 };");
    expect(APPLE_ICON).toContain('export const contentType = "image/png";');
    expect(APPLE_ICON).toContain("d={RING_PATH}");
    expect(APPLE_ICON).toContain("BRAND.accent");
    expect(APPLE_ICON).toContain("BRAND.paper");
  });

  it("needs no font, so a mark-only tile cannot fetch one", () => {
    expect(APPLE_ICON).not.toContain("fonts:");
    expect(APPLE_ICON).not.toContain("readFile");
  });
});

describe("the Open Graph image", () => {
  it("declares the share-card size, type and alt text", () => {
    expect(OPEN_GRAPH).toContain(
      "export const size = { width: 1200, height: 630 };",
    );
    expect(OPEN_GRAPH).toContain('export const contentType = "image/png";');
    expect(OPEN_GRAPH).toContain("export const alt = BRAND_OG_ALT;");
    expect(BRAND_OG_ALT.length).toBeGreaterThan(40);
  });

  it("carries the ring, the wordmark, the sentence and the stamp", () => {
    expect(OPEN_GRAPH).toContain("RING_PATH");
    expect(OPEN_GRAPH).toContain("{BRAND_DESCRIPTION}");
    expect(OPEN_GRAPH).toContain("{BRAND_STAMP}");
    expect(BRAND_DESCRIPTION).toBe(
      "A church-run break for a family that cares for someone.",
    );
    expect(BRAND_STAMP).toBe(
      "Fictional church, fictional families. Sample data.",
    );
    expect(OPEN_GRAPH).toContain("Respite");
    expect(OPEN_GRAPH).toContain("Circle");
  });

  it("passes the vendored Source Sans 3 family through fonts, offline", () => {
    // Static instances of the vendored faces: the renderer cannot read a
    // variable font. The instance files are cut from the vendored originals
    // and documented beside them.
    expect(OPEN_GRAPH).toContain('"SourceSans3-Regular.ttf"');
    expect(OPEN_GRAPH).toContain('"Fraunces-SemiBold.ttf"');
    expect(OPEN_GRAPH).toContain('name: "Source Sans 3"');
    expect(OPEN_GRAPH).toContain("fonts: [");
    expect(OPEN_GRAPH).toContain("data: sourceSans");
    expect(OPEN_GRAPH).not.toContain("fetch(");
    expect(OPEN_GRAPH).not.toMatch(/https?:\/\//);
  });

  it("shows no photograph and therefore no person", () => {
    expect(OPEN_GRAPH).not.toContain("<img");
    expect(OPEN_GRAPH).not.toMatch(/unsplash|images\//i);
  });
});

describe("the root metadata", () => {
  it("sets metadataBase from the deployment URL", () => {
    expect(LAYOUT).toContain("metadataBase: deploymentUrl()");
  });

  it("declares the icon, apple-touch and share routes", () => {
    expect(LAYOUT).toContain('url: "/icon.svg"');
    expect(LAYOUT).toContain('type: "image/svg+xml"');
    expect(LAYOUT).toContain('url: "/apple-icon"');
    expect(LAYOUT).toContain('sizes: "180x180"');
    expect(LAYOUT).toContain('url: "/opengraph-image"');
    expect(LAYOUT).toContain("width: 1200");
    expect(LAYOUT).toContain("height: 630");
  });

  it("declares Open Graph and Twitter cards with a title and description", () => {
    expect(LAYOUT).toContain("openGraph: {");
    expect(LAYOUT).toContain("title: BRAND_OG_TITLE");
    expect(LAYOUT).toContain("description: BRAND_DESCRIPTION");
    expect(LAYOUT).toContain('card: "summary_large_image"');
    expect(LAYOUT).toContain("twitter: {");
    expect(BRAND_OG_TITLE).toBe(
      "Respite Circle — a church-run break for a family that cares for someone",
    );
  });

  it("still exports no document title, so guarded routes cannot leak one", () => {
    expect(LAYOUT).not.toMatch(/^\s{2}title:/m);
    expect(LAYOUT).toContain("Deliberately no `title` here");
  });
});

describe("the masthead", () => {
  it("renders the ring at 28px beside the two-part wordmark", () => {
    expect(HEADER).toContain("<BrandMark className=\"h-7 w-7");
    // h-7 and w-7 are 28px at the default root size.
    expect(HEADER).toContain("Respite");
    expect(HEADER).toContain('className="font-medium italic text-accent"');
  });

  it("keeps the mark decorative with no role and no title", () => {
    expect(MARK_COMPONENT).toContain('aria-hidden="true"');
    // The prose above the function may name the forbidden attributes; the
    // markup itself must not carry them.
    expect(MARK_COMPONENT).not.toMatch(/<svg[\s\S]*?role=/);
    expect(MARK_COMPONENT).not.toMatch(/<svg[\s\S]*?<title/);
    expect(MARK_COMPONENT).toContain("RING_PATH");
  });

  it("puts the mark outside main, where page icons stay lucide-only", () => {
    // The header renders before the children, and the mark component is
    // imported only by the header.
    expect(LAYOUT.indexOf("<SiteHeader />")).toBeLessThan(
      LAYOUT.indexOf("{children}"),
    );
    expect(readText("src/app/(public)/page.tsx")).not.toContain("BrandMark");
  });
});

describe("deploymentUrl", () => {
  it("prefers the configured public app URL", () => {
    expect(
      deploymentUrl({
        NEXT_PUBLIC_APP_URL: "https://respite.example",
      }).toString(),
    ).toBe("https://respite.example/");
  });

  it("falls back to the Vercel production host, then the deployment host", () => {
    expect(
      deploymentUrl({
        VERCEL_PROJECT_PRODUCTION_URL: "respite-circle.vercel.app",
      }).toString(),
    ).toBe("https://respite-circle.vercel.app/");
    expect(
      deploymentUrl({
        VERCEL_URL: "respite-abc123.vercel.app",
      }).toString(),
    ).toBe("https://respite-abc123.vercel.app/");
  });

  it("ignores a malformed override and uses the local port", () => {
    expect(
      deploymentUrl({ NEXT_PUBLIC_APP_URL: "not a url" })
        .toString(),
    ).toBe("http://localhost:3130/");
  });

  it("refuses a non-http scheme", () => {
    expect(
      deploymentUrl({
        NEXT_PUBLIC_APP_URL: "javascript:alert(1)",
        VERCEL_URL: "respite-abc123.vercel.app",
      }).toString(),
    ).toBe("https://respite-abc123.vercel.app/");
  });
});


const SCRIPTS: Array<{ pattern: RegExp; code: string; confidence: number }> = [
  { pattern: /[\u0400-\u04ff]/, code: "cyrl", confidence: 0.97 },
  { pattern: /[\u0590-\u05ff]/, code: "hebr", confidence: 0.97 },
  { pattern: /[\u0600-\u06ff]/, code: "arab", confidence: 0.97 },
  { pattern: /[\u0370-\u03ff]/, code: "grek", confidence: 0.97 },
  { pattern: /[\u0900-\u097f]/, code: "deva", confidence: 0.97 },
  { pattern: /[\u0e00-\u0e7f]/, code: "thai", confidence: 0.97 },
  {
    pattern: /[\u3040-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uac00-\ud7af]/,
    code: "cjk",
    confidence: 0.97,
  },
];

const LANGUAGE_SETS: Array<{ code: string; words: Set<string> }> = Object.entries(
  LANGUAGE_WORDS,
).map(([code, words]) => ({ code, words: new Set(words) }));

const ENGLISH_SET = new Set(ENGLISH_WORDS);

function tokenise(text: string): string[] {
  return text
    .toLowerCase()
    .normalize("NFC")
    .match(/[\p{L}']+/gu)
    ?.filter((token) => token.length > 0) ?? [];
}

function countHits(tokens: readonly string[], words: Set<string>): number {
  const seen = new Set<string>();
  let hits = 0;
  for (const token of tokens) {
    if (words.has(token) && !seen.has(token)) {
      seen.add(token);
      hits += 1;
    }
  }
  return hits;
}

function isEnglishTag(language: string): boolean {
  return /^en\b/i.test(language.trim());
}

/**
 * Detect whether an ask is confidently not in English.
 *
 * A declared language wins for non-English intake. When the declared language
 * is English (or absent), a confident word/script signal can still override
 * it, so a mislabelled Spanish ask is never pushed into English slot guessing.
 */
export function detectLanguage(
  text: string,
  declaredLanguage?: string | null,
): LanguageDetection {
  const trimmed = text.trim();

  if (declaredLanguage && !isEnglishTag(declaredLanguage)) {
    return {
      code: declaredLanguage.trim().slice(0, 8).toLowerCase(),
      nonEnglish: true,
      confidence: 1,
      signals: 1,
    };
  }

  if (!trimmed) {
    return { code: "en", nonEnglish: false, confidence: 1, signals: 0 };
  }

  for (const script of SCRIPTS) {
    if (script.pattern.test(trimmed)) {
      return {
        code: script.code,
        nonEnglish: true,
        confidence: script.confidence,
        signals: 1,
      };
    }
  }

  const tokens = tokenise(trimmed);
  if (tokens.length === 0) {
    return { code: "en", nonEnglish: false, confidence: 0.5, signals: 0 };
  }

  const englishHits = countHits(tokens, ENGLISH_SET);

  let best = { code: "en", hits: 0 };
  for (const language of LANGUAGE_SETS) {
    const hits = countHits(tokens, language.words);
    if (hits > best.hits) best = { code: language.code, hits };
  }

  const confidentlyNonEnglish =
    best.hits >= 2 && best.hits > englishHits && best.code !== "en";

  if (!confidentlyNonEnglish) {
    return {
      code: "en",
      nonEnglish: false,
      confidence: Math.min(0.95, 0.5 + englishHits * 0.05),
      signals: englishHits,
    };
  }

  return {
    code: best.code,
    nonEnglish: true,
    confidence: Math.min(0.98, 0.55 + best.hits * 0.05),
    signals: best.hits,
  };
}
